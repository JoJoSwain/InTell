/**
 * M2a story-graph: Farmington geometry from fixture → seed-geometry.sql + demo-route.gpx
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  DWELL_KEYS,
  buildTrack,
  buildWaypoints,
  ll,
} from "./track.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "../..");
const fixture = JSON.parse(
  fs.readFileSync(
    path.join(root, "supabase/fixtures/farmington-bird-refuge.json"),
    "utf8",
  ),
);
const media = JSON.parse(
  fs.readFileSync(path.join(root, "supabase/seed-media.json"), "utf8"),
);

function wktPoint(p) {
  return `SRID=4326;POINT(${p.lng} ${p.lat})`;
}

function sqlStr(s) {
  return s.replace(/'/g, "''");
}

function cross(o, a, b) {
  return (a.lng - o.lng) * (b.lat - o.lat) - (a.lat - o.lat) * (b.lng - o.lng);
}

function convexHull(points) {
  const pts = [...points].sort((a, b) => a.lng - b.lng || a.lat - b.lat);
  if (pts.length <= 1) return pts;
  const lower = [];
  for (const p of pts) {
    while (
      lower.length >= 2 &&
      cross(lower[lower.length - 2], lower[lower.length - 1], p) <= 0
    )
      lower.pop();
    lower.push(p);
  }
  const upper = [];
  for (let i = pts.length - 1; i >= 0; i--) {
    const p = pts[i];
    while (
      upper.length >= 2 &&
      cross(upper[upper.length - 2], upper[upper.length - 1], p) <= 0
    )
      upper.pop();
    upper.push(p);
  }
  upper.pop();
  lower.pop();
  return lower.concat(upper);
}

// --- seed-geometry.sql ---
const trailPts = Object.entries(fixture.trail_points).map(([, v]) => ll(v));
const fragPts = fixture.fragments.map((f) => ll(f.at));
const allPts = [...trailPts, ...fragPts];
const hull = convexHull(allPts);
const hullRing = [...hull, hull[0]];
const hullWkt = `SRID=4326;POLYGON((${hullRing.map((p) => `${p.lng} ${p.lat}`).join(",")}))`;
const musicClipLng = -111.9235;

let sql = `-- GENERATED by tools/demo-geometry/generate.mjs — do not edit by hand
-- Source: supabase/fixtures/farmington-bird-refuge.json

drop table if exists public._seed_geometry;
create table public._seed_geometry (
  key text primary key,
  kind text not null,
  geog extensions.geography
);

insert into public._seed_geometry (key, kind, geog) values
  ('grove_boundary', 'polygon', extensions.ST_Buffer(extensions.ST_GeogFromText('${hullWkt}'), 50)),
  ('ambience_marsh', 'polygon', extensions.ST_Buffer(extensions.ST_GeogFromText('${hullWkt}'), 50)),
  ('music_zone', 'polygon', extensions.ST_Intersection(
     extensions.ST_Buffer(extensions.ST_GeogFromText('${hullWkt}'), 50)::extensions.geometry,
     extensions.ST_GeomFromText('POLYGON((${musicClipLng} -90, 180 -90, 180 90, ${musicClipLng} 90, ${musicClipLng} -90))', 4326)
   )::extensions.geography),
  ('region_bounds', 'polygon', extensions.ST_Buffer(extensions.ST_GeogFromText('${hullWkt}'), 500))
`;

for (const f of fixture.fragments) {
  const p = ll(f.at);
  sql += `,\n  ('${sqlStr(f.key)}', 'point', extensions.ST_GeogFromText('${wktPoint(p)}'))`;
}
sql += ";\n";

fs.writeFileSync(path.join(root, "supabase/seed-geometry.sql"), sql);

// --- GPX (dwell on arrival, before leaving) ---
const waypoints = buildWaypoints(fixture);
const track = buildTrack(waypoints, DWELL_KEYS, media);

const t0 = Date.UTC(2026, 5, 15, 17, 0, 0);
const trkpts = track.map((p, i) => {
  const t = new Date(t0 + i * 1000).toISOString();
  return `      <trkpt lat="${p.lat.toFixed(8)}" lon="${p.lng.toFixed(8)}"><ele>1285</ele><time>${t}</time></trkpt>`;
});

const gpx = `<?xml version="1.0" encoding="UTF-8"?>
<gpx version="1.1" creator="InTell tools/demo-geometry" xmlns="http://www.topografix.com/GPX/1/1">
  <metadata>
    <name>Farmington Bird Refuge demo route</name>
    <desc>Generated from supabase/fixtures/farmington-bird-refuge.json. Never enters frag9 radius.</desc>
  </metadata>
  <trk>
    <name>demo-route</name>
    <trkseg>
${trkpts.join("\n")}
    </trkseg>
  </trk>
</gpx>
`;

const gpxPath = path.join(root, "apps/mobile/e2e/demo-route.gpx");
fs.mkdirSync(path.dirname(gpxPath), { recursive: true });
fs.writeFileSync(gpxPath, gpx);

const meta = {
  pointCount: track.length,
  durationSec: track.length,
  first10: trkpts.slice(0, 10),
  last10: trkpts.slice(-10),
};
fs.writeFileSync(
  path.join(root, "tools/demo-geometry/last-gpx-meta.json"),
  JSON.stringify(meta, null, 2),
);

console.log(
  `Wrote seed-geometry.sql + GPX (${track.length} points, ${track.length}s)`,
);
